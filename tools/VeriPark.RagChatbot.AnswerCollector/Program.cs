using System.Net.Http.Json;
using System.Text;
using System.Text.Json;
using VeriPark.RagChatbot.AnswerCollector;

// Asks the seven assessment questions through the running chatbot (one single conversation, so question 6
// and question 7 can refer to earlier turns) and writes the chatbot's own answers to a Markdown file.
//
// Usage: dotnet run --project tools/VeriPark.RagChatbot.AnswerCollector -- [--url http://localhost:5080] [--output assessment_answers.md]

var baseUrl = GetArgument(args, "--url") ?? "http://localhost:5080";
var outputPath = GetArgument(args, "--output") ?? "assessment_answers.md";
var conversationId = $"assessment-{DateTime.UtcNow:yyyyMMddHHmmss}";

var jsonOptions = new JsonSerializerOptions(JsonSerializerDefaults.Web);
using var http = new HttpClient { BaseAddress = new Uri(baseUrl), Timeout = TimeSpan.FromMinutes(3) };

Console.WriteLine($"Chatbot URL : {baseUrl}");
Console.WriteLine($"Output file : {Path.GetFullPath(outputPath)}");
Console.WriteLine();

if (!await WaitUntilReadyAsync(http, jsonOptions))
{
    Console.Error.WriteLine("The chatbot is not ready. Is Qdrant running and are the Azure OpenAI settings correct? Check the API console.");
    return 1;
}

var markdown = new StringBuilder();
markdown.AppendLine("# Assessment Answers");
markdown.AppendLine();
markdown.AppendLine("Every answer below was generated by the C# / .NET RAG chatbot in this project (Semantic Kernel + Qdrant + Azure OpenAI).");
markdown.AppendLine("All seven questions were asked in one conversation, in order, through the chatbot's `POST /api/chat` endpoint.");
markdown.AppendLine();
markdown.AppendLine($"- Generated (UTC): {DateTime.UtcNow:yyyy-MM-dd HH:mm}");
markdown.AppendLine($"- Conversation id: `{conversationId}`");
markdown.AppendLine();

for (var i = 0; i < AssessmentQuestions.All.Count; i++)
{
    var number = i + 1;
    var question = AssessmentQuestions.All[i];
    Console.WriteLine($"Question {number}/{AssessmentQuestions.All.Count}: {question}");

    using var httpResponse = await http.PostAsJsonAsync("/api/chat", new ChatRequest(conversationId, question), jsonOptions);
    if (!httpResponse.IsSuccessStatusCode)
    {
        var body = await httpResponse.Content.ReadAsStringAsync();
        Console.Error.WriteLine($"Request failed ({(int)httpResponse.StatusCode}): {body}");
        return 1;
    }

    var response = await httpResponse.Content.ReadFromJsonAsync<ChatResponse>(jsonOptions)
        ?? throw new InvalidOperationException("Empty response from chatbot.");

    Console.WriteLine(response.Answer);
    Console.WriteLine();

    markdown.AppendLine($"## Question {number}");
    markdown.AppendLine();
    markdown.AppendLine($"> {question}");
    markdown.AppendLine();
    markdown.AppendLine("**Chatbot answer:**");
    markdown.AppendLine();
    markdown.AppendLine(response.Answer);
    markdown.AppendLine();

    var pages = response.Citations.Select(c => c.PageNumber).Distinct().Order().ToList();
    if (pages.Count > 0)
    {
        markdown.AppendLine($"*Sources (document pages): {string.Join(", ", pages)}*");
        markdown.AppendLine();
    }
}

await File.WriteAllTextAsync(outputPath, markdown.ToString(), new UTF8Encoding(false));
Console.WriteLine($"Saved {AssessmentQuestions.All.Count} answers to {Path.GetFullPath(outputPath)}");
return 0;

static string? GetArgument(string[] args, string name)
{
    var index = Array.IndexOf(args, name);
    return index >= 0 && index + 1 < args.Length ? args[index + 1] : null;
}

static async Task<bool> WaitUntilReadyAsync(HttpClient http, JsonSerializerOptions jsonOptions)
{
    const int maxAttempts = 60; // about 2 minutes
    for (var attempt = 1; attempt <= maxAttempts; attempt++)
    {
        try
        {
            var health = await http.GetFromJsonAsync<HealthResponse>("/health", jsonOptions);
            if (health is { IsReady: true })
            {
                Console.WriteLine($"Chatbot is ready ({health.ChunkCount} chunks in Qdrant).");
                return true;
            }

            Console.WriteLine($"Waiting for ingestion... status: {health?.Status}");
        }
        catch (HttpRequestException)
        {
            Console.WriteLine("Waiting for the API to start...");
        }

        await Task.Delay(TimeSpan.FromSeconds(2));
    }

    return false;
}
